#!/usr/bin/env python3
"""
CUDA throughput: run an already compiled cuda-k-means on every input file of
a directory and compute its throughput.

The input files should be generated by inputgen with the same n_dims,
n_clusters and seed, changing only points_per_cluster (see bench_omp.py).

Usage:
  ./bench/bench_cuda.py EXE K input_dir output_file [--out-dir DIR]

  EXE          compiled program, e.g. ./cuda-k-means
  K            number of clusters
  input_dir    directory with the input files (*.txt)
  output_file  k-means output file (passed to the program)
  --out-dir    where to save metrics.txt and the plots (default: bench/results/cuda)

Each run is:  EXE K input output_file
The program prints "Elapsed time" (main loop, no I/O), "Overhead time"
(context creation, kernel loading, device allocation, host<->device copies)
and "Total time" (their sum).

Metrics, for each input file:
  N_operations   = iterations * N * K * D
                   asymptotic cost of the main loop: every iteration computes,
                   for each of the N points, the distance (D dimensions) to the
                   K centroids, O(N*K*D); the centroid update is O(N*D), a
                   lower-order term
  throughput     = N_operations / wall-clock time   (ops/s, on "Elapsed time")
  throughput incl. overhead = N_operations / "Total time"

Plots (x axis: number of points N):
  cuda_time.png        main loop T, overhead and total time
  cuda_throughput.png  throughput without overhead (T) and with overhead (total)

Before running it, run the program once (e.g. on the smallest input): the
first run after compiling also compiles the GPU code for your GPU, which
inflates its overhead.

Example:
  ./bench/bench_cuda.py ./cuda-k-means 10 inputs/ out.txt
"""

import argparse
import os
import re
import subprocess
from pathlib import Path

COLORS = ["#2a78d6", "#eb6834", "#1baf7a"]      # reference palette, fixed order
INK2 = "#52514e"
SURFACE, GRID, AXIS = "#fcfcfb", "#e1e0d9", "#c3c2b7"


def input_shape(path):
    """(N, D): number of points and dimensions of an input file."""
    n, d = 0, None
    with open(path) as f:
        for line in f:
            if line.strip():
                n += 1
                if d is None:
                    d = len(line.split())
    return n, d


def run(exe, k, input_file, output_file):
    """Run the program; return (elapsed, overhead, total, iterations)."""
    if os.path.isfile(exe):                 # "cuda-k-means" in the current folder, not in PATH
        exe = os.path.abspath(exe)
    out = subprocess.run([exe, str(k), str(input_file), output_file],
                         capture_output=True, text=True, check=True).stdout

    def grab(label):
        m = re.search(rf"^{label}\s+([0-9.]+)", out, re.M)
        return float(m.group(1)) if m else None

    elapsed = grab("Elapsed time")
    if elapsed is None:
        raise SystemExit(f"no 'Elapsed time' in the output of {exe}")
    return (elapsed, grab("Overhead time"), grab("Total time"),
            len(re.findall(r"^Iteration", out, re.M)))


def report(rows):
    lines = [f"{'N':>10} {'D':>4} {'iters':>6} {'T [s]':>9} {'overhead [s]':>13} {'total [s]':>10} "
             f"{'N_operations':>14} {'throughput [ops/s]':>19} {'incl. overhead [ops/s]':>23}"]
    for r in rows:
        f = lambda v, spec: "NA" if v is None else format(v, spec)
        lines.append(f"{r['n']:>10,} {r['d']:>4} {r['iters']:>6} {f(r['elapsed'], '.4f'):>9} "
                     f"{f(r['overhead'], '.4f'):>13} {f(r['total'], '.4f'):>10} "
                     f"{r['ops']:>14.4e} {f(r['throughput'], '.4e'):>19} "
                     f"{f(r['throughput_total'], '.4e'):>23}")
    return "\n".join(lines)


def plot(rows, out_dir):
    """Time and throughput as a function of the number of points N."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("plots skipped: pip install --user matplotlib")
        return
    plt.rcParams.update({"font.size": 11, "axes.labelsize": 12, "legend.fontsize": 10})
    x = [r["n"] for r in rows]

    def fig(name, ylabel, series):
        f, ax = plt.subplots(figsize=(7.5, 4.6))
        f.patch.set_facecolor(SURFACE)
        ax.set_facecolor(SURFACE)
        ax.set_xlabel("number of points N", color=INK2, labelpad=6)
        ax.set_ylabel(ylabel, color=INK2, labelpad=6)
        ax.set_xticks(x)
        ax.set_xticklabels([f"{n // 1000:,}k" for n in x])
        ax.tick_params(colors=INK2, length=3)
        ax.grid(color=GRID, linewidth=0.6)
        ax.set_axisbelow(True)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        for side in ("left", "bottom"):
            ax.spines[side].set_color(AXIS)
        for label, key, color in series:
            ax.plot(x, [r[key] for r in rows], "-o", color=color, linewidth=2.2, markersize=7,
                    markeredgecolor=SURFACE, markeredgewidth=1.5, label=label)
        ax.set_ylim(bottom=0)
        ax.legend(frameon=False, loc="best")
        f.tight_layout()
        f.savefig(out_dir / f"{name}.png", dpi=150)
        plt.close(f)
        print(f"plot: {out_dir / (name + '.png')}")

    fig("cuda_time", "time [s]", [("main loop T", "elapsed", COLORS[0]),
                                  ("overhead", "overhead", COLORS[1]),
                                  ("total", "total", COLORS[2])])
    fig("cuda_throughput", "throughput [ops/s]",
        [("without overhead (T)", "throughput", COLORS[0]),
         ("with overhead (total)", "throughput_total", COLORS[1])])


def main():
    ap = argparse.ArgumentParser(description="CUDA throughput",
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__)
    ap.add_argument("exe", help="compiled program, e.g. ./cuda-k-means")
    ap.add_argument("K", type=int, help="number of clusters")
    ap.add_argument("input_dir", help="directory with the input files (*.txt)")
    ap.add_argument("output_file")
    ap.add_argument("--out-dir", default=str(Path(__file__).parent / "results" / "cuda"),
                    help="where to save metrics.txt and the plots")
    args = ap.parse_args()

    files = sorted(Path(args.input_dir).glob("*.txt"))
    if not files:
        raise SystemExit(f"no *.txt input files in {args.input_dir}")
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    for path in files:
        n, d = input_shape(path)
        elapsed, overhead, total, iters = run(args.exe, args.K, path, args.output_file)
        ops = iters * n * args.K * d
        rows.append({"n": n, "d": d, "iters": iters, "elapsed": elapsed, "overhead": overhead,
                     "total": total, "ops": ops,
                     "throughput": ops / elapsed if elapsed else None,
                     "throughput_total": ops / total if total else None})
        print(f"N={n:<9,} T = {elapsed:.4f} s  ({iters} iterations)")
    rows.sort(key=lambda r: r["n"])

    text = (f"CUDA throughput: {args.exe}, K={args.K}, inputs from {args.input_dir}\n"
            f"N_operations = iterations * N * K * D (asymptotic cost of the main loop)\n"
            f"throughput = N_operations / wall-clock time (Elapsed time); "
            f"incl. overhead = N_operations / Total time\n\n{report(rows)}\n")
    if any(r["elapsed"] == 0 for r in rows):
        text += ("\nNOTE: some wall-clock times are 0.000 (the program prints 3 decimals):"
                 " their throughput is NA.\n")
    (out_dir / "metrics.txt").write_text(text)
    print("\n" + text + f"\nmetrics: {out_dir / 'metrics.txt'}")
    plot(rows, out_dir)


if __name__ == "__main__":
    main()
