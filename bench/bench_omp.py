#!/usr/bin/env python3
"""
OpenMP scaling: run an already compiled omp-k-means on every input file of a
directory with p = 1, 2, 4, 6, 8, ..., T threads (every 2) and plot the metrics.

The input files should be generated by inputgen with the same n_dims,
n_clusters and seed, changing only points_per_cluster, so that they differ
only by the number of points N (same clustering problem, more points), e.g.

  mkdir inputs
  for P in 5000 10000 20000; do ./inputgen $P 20 10 > inputs/N$((P*10)).txt; done

Usage:
  ./bench/bench_omp.py EXE T K input_dir output_file [--out-dir DIR]

  EXE          compiled program, e.g. ./omp-k-means
  T            maximum number of threads
  K            number of clusters
  input_dir    directory with the input files (*.txt)
  output_file  k-means output file (passed to the program)
  --out-dir    where to save metrics.txt and the plots (default: bench/results)

Each run is:  OMP_NUM_THREADS=p OMP_PROC_BIND=close OMP_PLACES=cores EXE K input output_file
and T(p) is the "Elapsed time" printed by the program (main loop, no I/O).

Metrics, for each input file (T_serial = T(1), the program run with 1 thread):
  wall-clock time   T(p)
  speedup           S(p) = T(1) / T(p)
  efficiency        E(p) = T(1) / (p * T(p))
  overhead          O(p) = T(p) - T(1) / p     (estimated)

Plots (one line per input file, legend = N): omp_time.png, omp_speedup.png,
omp_efficiency.png, omp_overhead.png. Each line is the strong scaling of one
input; comparing the lines (larger N with more threads) shows the weak scaling.
The plots mark where SMT starts (more threads than physical cores).

Example:
  ./bench/bench_omp.py ./omp-k-means 12 10 inputs/ out.txt
"""

import argparse
import os
import re
import subprocess
from pathlib import Path

# Reference palette: one fixed color per input file, in order (never cycled).
COLORS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300"]
INK, INK2 = "#0b0b0b", "#52514e"
SURFACE, GRID, AXIS = "#fcfcfb", "#e1e0d9", "#c3c2b7"


def thread_list(t_max):
    """1, then every 2 threads (2, 4, 6, 8, ...) up to t_max (always included)."""
    ts = [1] + list(range(2, t_max + 1, 2))
    if ts[-1] != t_max:
        ts.append(t_max)
    return ts


def physical_cores():
    """Number of physical cores (from lscpu); beyond it, threads share a core (SMT)."""
    try:
        out = subprocess.run(["lscpu", "-p=CORE,SOCKET"], capture_output=True, text=True).stdout
        cores = {l for l in out.splitlines() if l and not l.startswith("#")}
        return len(cores) or os.cpu_count()
    except OSError:
        return os.cpu_count()


def count_points(path):
    with open(path) as f:
        return sum(1 for line in f if line.strip())


def run(exe, p, k, input_file, output_file):
    """Run the program with p threads; return the printed Elapsed time.
    Threads are pinned, one per physical core: without it the OS moves them
    around and T(p) varies a lot from run to run."""
    env = dict(os.environ, OMP_NUM_THREADS=str(p), OMP_PROC_BIND="close", OMP_PLACES="cores")
    if os.path.isfile(exe):                 # "omp-k-means" in the current folder, not in PATH
        exe = os.path.abspath(exe)
    out = subprocess.run([exe, str(k), str(input_file), output_file],
                         env=env, capture_output=True, text=True, check=True).stdout
    m = re.search(r"Elapsed time\s+([0-9.]+)", out)
    if m is None:
        raise SystemExit(f"no 'Elapsed time' in the output of {exe}")
    return float(m.group(1))


def report(inputs):
    lines = []
    for inp in inputs:
        lines.append(f"\n{inp['name']}  (N = {inp['n']:,})")
        lines.append(f"{'p':>4} {'T(p) [s]':>10} {'speedup':>8} {'efficiency':>10} {'overhead [s]':>12}")
        for r in inp["rows"]:
            lines.append(f"{r['p']:>4} {r['time']:>10.4f} {r['speedup']:>8.3f} "
                         f"{r['efficiency']:>10.3f} {r['overhead']:>12.4f}")
    return "\n".join(lines)


def plot(inputs, out_dir):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("plots skipped: pip install --user matplotlib")
        return
    plt.rcParams.update({"font.size": 11, "axes.labelsize": 12, "legend.fontsize": 10})
    x_all = sorted({r["p"] for inp in inputs for r in inp["rows"]})
    phys = physical_cores()

    def fig(name, ylabel, key, ideal=None, ylim_bottom=0):
        f, ax = plt.subplots(figsize=(7.5, 4.6))
        f.patch.set_facecolor(SURFACE)
        ax.set_facecolor(SURFACE)
        ax.set_xlabel("threads p", color=INK2, labelpad=6)
        ax.set_ylabel(ylabel, color=INK2, labelpad=6)
        ax.set_xticks(x_all)
        ax.set_xlim(min(x_all) - 0.6, max(x_all) + 0.6)
        ax.tick_params(colors=INK2, length=3)
        ax.grid(color=GRID, linewidth=0.6)
        ax.set_axisbelow(True)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        for side in ("left", "bottom"):
            ax.spines[side].set_color(AXIS)
        if ideal is not None:
            ax.plot(x_all, ideal(x_all), "--", color=INK2, linewidth=1.3, zorder=2, label="ideal")
        for inp, color in zip(inputs, COLORS):
            ax.plot([r["p"] for r in inp["rows"]], [r[key] for r in inp["rows"]], "-o",
                    color=color, linewidth=2.2, markersize=7, markeredgecolor=SURFACE,
                    markeredgewidth=1.5, zorder=3, label=f"N = {inp['n']:,}")
        if phys < max(x_all):               # right of this line, threads share a core
            ax.axvline(phys, color=INK, linestyle="-.", linewidth=1.4, zorder=5,
                       label=f"SMT starts ({phys} physical cores)")
        if ylim_bottom is not None:
            ax.set_ylim(bottom=ylim_bottom)
        ax.legend(frameon=False, loc="best")
        f.tight_layout()
        f.savefig(out_dir / f"{name}.png", dpi=150)
        plt.close(f)
        print(f"plot: {out_dir / (name + '.png')}")

    min_overhead = min(r["overhead"] for inp in inputs for r in inp["rows"])
    fig("omp_time", "wall-clock time [s]", "time")
    fig("omp_speedup", "speedup", "speedup", ideal=lambda x: x)
    fig("omp_efficiency", "efficiency", "efficiency", ideal=lambda x: [1] * len(x))
    fig("omp_overhead", "overhead [s]", "overhead", ylim_bottom=min(0, min_overhead * 1.1))


def main():
    ap = argparse.ArgumentParser(description="OpenMP scaling",
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__)
    ap.add_argument("exe", help="compiled program, e.g. ./omp-k-means")
    ap.add_argument("T", type=int, help="maximum number of threads")
    ap.add_argument("K", type=int, help="number of clusters")
    ap.add_argument("input_dir", help="directory with the input files (*.txt)")
    ap.add_argument("output_file")
    ap.add_argument("--out-dir", default=str(Path(__file__).parent / "results"),
                    help="where to save metrics.txt and the plots")
    args = ap.parse_args()

    files = sorted(Path(args.input_dir).glob("*.txt"))
    if not files:
        raise SystemExit(f"no *.txt input files in {args.input_dir}")
    if len(files) > len(COLORS):
        raise SystemExit(f"{len(files)} input files: at most {len(COLORS)} (one color each)")
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    inputs = sorted(({"name": f.name, "path": f, "n": count_points(f)} for f in files),
                    key=lambda inp: inp["n"])
    for inp in inputs:
        inp["rows"] = []
        for p in thread_list(args.T):
            t = run(args.exe, p, args.K, inp["path"], args.output_file)
            print(f"N={inp['n']:<9,} p={p:<3} T(p) = {t:.4f} s")
            inp["rows"].append({"p": p, "time": t})
        t1 = inp["rows"][0]["time"]                  # T_serial = T(1)
        for r in inp["rows"]:
            p = r["p"]
            r["speedup"] = t1 / r["time"] if r["time"] else float("nan")
            r["efficiency"] = r["speedup"] / p
            r["overhead"] = r["time"] - t1 / p

    text = (f"OpenMP scaling: {args.exe}, K={args.K}, inputs from {args.input_dir}\n"
            f"T_serial = T(1); speedup = T(1)/T(p); efficiency = T(1)/(p*T(p)); "
            f"overhead = T(p) - T(1)/p\n{report(inputs)}\n")
    (out_dir / "metrics.txt").write_text(text)
    print(text + f"\nmetrics: {out_dir / 'metrics.txt'}")
    plot(inputs, out_dir)


if __name__ == "__main__":
    main()
